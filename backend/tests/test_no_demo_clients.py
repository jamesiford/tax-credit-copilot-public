"""The app works with whatever accounts the source holds, and knows none by name. [04]

Every dataset here uses ids and names the product has never heard of, plus a source with no account 1001, an
empty source and a crowded one. The fixture's own account is declared by configuration, the certified
reference is identified only by `REFERENCE_ACCOUNT_ID`, and nothing derives "synthetic" from an id range.
"""
from __future__ import annotations

import dataclasses

import pytest
from fastapi.testclient import TestClient
from local_lakehouse import use_local_lakehouse, write_lakehouse

from application import client_book, warmup
from data import designations
from data.source import from_fabric
from data.source.synth import SYNTHETIC_CLIENTS, build_synthetic_dataset

UNFAMILIAR_ID = 7
UNFAMILIAR_NAME = "Example Client Z"


@pytest.fixture
def lake(tmp_path, monkeypatch):
    spec = dataclasses.replace(SYNTHETIC_CLIENTS[0], account_id=UNFAMILIAR_ID, name=UNFAMILIAR_NAME)
    write_lakehouse(tmp_path, build_synthetic_dataset(spec), schema="tcc_source")
    use_local_lakehouse(monkeypatch, tmp_path)
    for name, value in (("DATA_SOURCE", "lakehouse"), ("FABRIC_WORKSPACE", "ws"), ("FABRIC_LAKEHOUSE", "lh"), ("PAY_CODE_POLICY", "assume"),
                        ("DATA_CLASSIFICATION", "customer")):
        monkeypatch.setenv(name, value)
    monkeypatch.setattr("infrastructure.persistence.source_sql.SourceSqlReader.is_configured", lambda self: False)
    yield
    from_fabric.clear_cache()


def test_a_source_with_one_unfamiliar_account_lists_exactly_that_account(lake):
    (only,) = client_book.clients()
    assert only["account_id"] == UNFAMILIAR_ID and only["name"] == UNFAMILIAR_NAME
    assert only["synthetic"] is False, "customer-classified data is never labelled generated by its id"


def test_that_account_has_payroll_and_a_call_that_names_no_tenant_has_none(lake):
    from infrastructure.payroll import pay_period_source as source

    assert source.load_pay_periods(UNFAMILIAR_ID)
    assert source.load_pay_periods(None) == [], "no tenant named: nobody's payroll, not a configured default's"
    assert set(source.load_portfolio_pay_periods()) == {UNFAMILIAR_ID}


def test_an_empty_source_is_an_empty_book_not_an_error(monkeypatch):
    monkeypatch.setenv("DATA_SOURCE", "lakehouse")
    monkeypatch.setattr(client_book, "accounts_from_warehouse", lambda: [])
    assert client_book.clients() == []
    from main import app

    body = TestClient(app, raise_server_exceptions=False).get("/api/v2/portfolio")
    assert body.status_code == 200 and body.json()["items"] == []


def test_a_crowded_source_lists_every_account_and_none_by_default(monkeypatch):
    monkeypatch.setenv("DATA_SOURCE", "lakehouse")
    accounts = [{"AccountId": 9000 + i, "Name": f"Client {i:03d}"} for i in range(50)]
    monkeypatch.setattr(client_book, "accounts_from_warehouse", lambda: accounts)
    book = client_book.clients()
    assert len(book) == 50 and all(c["account_id"] != 1001 for c in book)


@pytest.mark.parametrize(("classification", "marker", "expected"), [
    ("customer", None, False), ("customer", True, True), ("synthetic", None, True), ("synthetic", False, False),
])
def test_synthetic_comes_from_the_data_or_the_environment_never_an_id(monkeypatch, classification, marker, expected):
    monkeypatch.setenv("DATA_SOURCE", "lakehouse")
    monkeypatch.setenv("DATA_CLASSIFICATION", classification)
    account = {"AccountId": 5000, "Name": "Any"} | ({} if marker is None else {"IsSynthetic": marker})
    monkeypatch.setattr(client_book, "accounts_from_warehouse", lambda: [account])
    assert client_book.clients()[0]["synthetic"] is expected


def test_no_designation_is_invented_for_a_customer_account_whatever_its_id(monkeypatch):
    monkeypatch.setenv("DATA_CLASSIFICATION", "customer")
    assert designations.designation_history("GA_GA-001", 2500) == []
    monkeypatch.setenv("DATA_CLASSIFICATION", "synthetic")
    assert designations.designation_history("GA_GA-001", 2500)[0]["tier"] == 1


def test_a_fixture_source_with_no_declared_account_has_no_clients(monkeypatch):
    monkeypatch.setenv("DATA_SOURCE", "csv")
    monkeypatch.delenv("FIXTURE_ACCOUNT_ID")
    from infrastructure.payroll import pay_period_source as source

    assert client_book.clients() == [] and source.load_portfolio_pay_periods() == {}
    monkeypatch.setenv("FIXTURE_ACCOUNT_ID", "55")
    assert [c["account_id"] for c in client_book.clients()] == [55]
    assert list(source.load_portfolio_pay_periods()) == [55]


@pytest.mark.parametrize(("listed", "warm", "expected"), [
    ([11, 12, 13, 14, 15], "3", [11, 12, 13]), ([21], "3", [21]), ([], "3", []), ([31, 32], "0", []),
])
def test_warm_up_takes_a_bounded_prefix_of_what_the_source_lists(monkeypatch, listed, warm, expected):
    monkeypatch.setenv("WARM_CLIENTS", warm)
    assert warmup._warm_account_ids([{"AccountId": i} for i in listed]) == expected


def test_the_sealed_reference_needs_a_configured_account_and_says_so(monkeypatch):
    monkeypatch.delenv("REFERENCE_ACCOUNT_ID")
    from application.errors import ReferenceNotConfigured
    from tools.reference_workspace import ReferenceWorkspaceService

    with pytest.raises(ReferenceNotConfigured) as caught:
        ReferenceWorkspaceService().get()
    assert caught.value.dependency == "reference_dataset" and "REFERENCE_ACCOUNT_ID" in caught.value.remedy
    assert warmup._reference_configured() is False
    monkeypatch.setenv("REFERENCE_ACCOUNT_ID", "42")
    assert warmup._reference_configured() is True
