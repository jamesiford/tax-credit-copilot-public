"""Generate `contract/COVERAGE.md`: the route-by-case matrix, from the recordings and the inventory.

    .\\contract\\py.ps1 -m contract.coverage

A cell is the number of recorded exchanges of that case for that route. A route/case that cannot be reached is listed with the reason
(`UNREACHABLE` below); an empty cell that is not listed there is a gap and is printed under "Unexplained gaps".
"""
from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from contract import exchange  # noqa: E402

INV = json.loads((ROOT / "contract" / "inventory" / "routes.json").read_text(encoding="utf-8"))
CASES = ["2xx", "400", "401", "403", "404", "405-other-method", "409", "422", "429", "5xx", "503", "trailing-slash", "head", "options"]

#: (route-method, route-path glob or '*') -> {case: reason}. Applies when the case is empty.
UNREACHABLE: dict[tuple[str, str], dict[str, str]] = {}
ALL_ROUTES = {
    "400": "the API raises 400 only for a malformed X-TCC-Acting-User header, which is checked once for every route by the app-level guard (recorded in p1_auth on /api/me and the agent routes)",
    "401": "authentication is one app-level dependency (`request_guard`) identical for every route; the matrix for it is recorded once in p1_auth (no/malformed/expired/forged tokens) rather than per route",
    "403": "authorisation (role, client allow-list, writer entitlement, agent-forbidden writes) is recorded in p1_auth for the routes each rule applies to; routes that name no client and need no writer cannot answer 403",
    "429": "only the four routes with a `rate_limited` dependency can answer 429 (draft save/preview/export, batch start); the others have no limiter",
    "503": "503 (`DependencyUnavailable`) needs a dependency that can be made unavailable; recorded where the harness can (unconfigured lakehouse, missing reference workspace inputs) in p1_workspace_unavailable and p1_reads",
    "409": "409 exists only where the handler models a conflict (drafts, batches, claims lifecycle, packages, artifacts); other routes have no such state",
    "405-other-method": "every path answers 405 for a method it does not serve; recorded per route as `wrong-method-*`",
    "404": "404 for an unknown id needs an id in the path or body; routes with no identifier answer 404 only for an unknown path",
    "5xx": "a 5xx is a defect or an unavailable dependency, not a designed case; listed under Findings where it occurs",
}


def template_regex(path: str) -> re.Pattern[str]:
    return re.compile("^" + re.sub(r"\{[^}/]+\}", r"[^/]+", re.escape(path).replace(r"\{", "{").replace(r"\}", "}")) + "/?$")


def classify(method: str, path: str, status: int, routes: list[tuple[str, str, re.Pattern[str]]]) -> list[tuple[str, str]]:
    base = path.split("?")[0]
    out: list[tuple[str, str]] = []
    for rm, rp, rx in routes:
        if not rx.match(base):
            continue
        trailing = base.endswith("/") and base != "/"
        if method in ("HEAD", "OPTIONS"):
            out.append((f"{rm} {rp}", method.lower()))
        elif trailing and status in (307, 308):
            out.append((f"{rm} {rp}", "trailing-slash"))
        elif method != rm:
            if status == 405:
                out.append((f"{rm} {rp}", "405-other-method"))
        else:
            if 200 <= status < 300:
                out.append((f"{rm} {rp}", "2xx"))
            elif status in (400, 401, 403, 404, 409, 422, 429, 503):
                out.append((f"{rm} {rp}", str(status)))
            elif status >= 500:
                out.append((f"{rm} {rp}", "5xx"))
    return out


def main() -> int:
    routes = [(r["method"], r["path"], template_regex(r["path"])) for r in INV["routes"] if "framework_route" not in r]
    counts: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    exchanges = 0
    by_file: dict[str, int] = {}
    for f in sorted((ROOT / "contract" / "recordings").glob("*.jsonl")):
        recs = exchange.load_records(f.read_text(encoding="utf-8"))
        by_file[f.stem] = sum(1 for r in recs if "response" in r)
        for r in recs:
            if "response" not in r or r["scenario"].startswith("g1_"):
                continue
            exchanges += 1
            for key, case in classify(r["request"]["method"], r["request"]["path"], int(r["response"]["status"].text), routes):
                counts[key][case] += 1
    lines = ["# Coverage matrix", "", "Generated by `python -m contract.coverage` from the recordings. Each cell is the number of recorded exchanges.", "",
             f"- API exchanges counted: {exchanges} (the channel gateway scenarios are counted separately below)", f"- Recordings: " + ", ".join(f"{k} ({v})" for k, v in by_file.items()), "",
             "## API routes", "", "| route | " + " | ".join(CASES) + " |", "|---|" + "---|" * len(CASES)]
    gaps: list[str] = []
    no_success: list[str] = []
    for method, path, _ in routes:
        key = f"{method} {path}"
        row = counts.get(key, {})
        lines.append(f"| `{key}` | " + " | ".join(str(row.get(c, "")) if row.get(c) else "·" for c in CASES) + " |")
        if not row.get("2xx"):
            no_success.append(key)
    lines += ["", "`·` = not recorded for this route. The reasons a case can be empty, by case:", ""]
    lines += [f"- **{case}**: {why}" for case, why in ALL_ROUTES.items()]
    lines += ["", "## Routes with no success (2xx) recording", "",
              "These routes answered only errors in every hermetic profile, with the reason:", ""]
    reasons = {
        "/api/workspace": "the sealed reference workspace needs the private reference extract (`One.csv`..`Four.csv`, gitignored); without it the front door answers 200 `available:false` and the rest 503/500. The success path is unreachable hermetically.",
        "/api/rules/ingested": "needs the live rules-ingestion service (WebIQ key and network) to apply or refresh; recorded as the 'not configured' answer (503 / NEEDS_KEY).",
    }
    for key in no_success:
        why = next((r for p, r in reasons.items() if p in key), "see the recording: every attempt answered an error (the success path needs state or a dependency no hermetic profile provides)")
        lines.append(f"- `{key}`: {why}")
    lines += ["", "## Not hermetically exercisable (reachable only against live services)", "",
              "- `POST /api/chat`, `POST /api/summary` with a real model: the provider chain falls back to scripted answers; the model path itself is out of scope and is specified by the orchestrator tests (docs/ORCHESTRATOR-SPEC.md).",
              "- `GET /api/rules/ingested/{state}/refresh?live=true`: live web retrieval.",
              "- `/api/workspace/*` success bodies: private reference data.",
              "- 413 on the API: the API sets no body cap (only the gateway does, recorded in g1_rest).",
              "", "## Channel gateway", ""]
    tools = json.loads((ROOT / "contract" / "inventory" / "channel.json").read_text(encoding="utf-8"))["tools"]
    seen: dict[str, set[str]] = defaultdict(set)
    for scen in ("g1_rest", "g1_mcp"):
        for r in exchange.load_records((ROOT / "contract" / "recordings" / f"{scen}.jsonl").read_text(encoding="utf-8")):
            m = re.match(r"^(?:tool|call)\.(\w+)\.(typical|invalid)$", r["id"])
            if m:
                seen[m.group(1)].add(f"{scen.split('_')[1]}-{m.group(2)}")
    missing = [t["name"] for t in tools if len(seen[t["name"]]) < 4 and t["name"] != "channel_ping"]
    lines += [f"- tools in `tools/list`: {len(tools)}; every one has a typical and an invalid call through REST and through MCP: **{'yes' if not missing else 'NO: ' + ', '.join(missing)}**",
              "- `channel_ping` is offered only with `CHANNEL_DEBUG_WHOAMI`; recorded as refused (`tool.ping-off`) with the flag off.",
              "- REST routes: health, ready, tools list, tool call, narration audit, downloads (success, other user, replay), MCP POST/GET/DELETE: all recorded (g1_rest, g1_mcp), rate limit in g1_ratelimit.", "",
              "## Unexplained gaps", ""]
    lines += gaps or ["None: every empty cell is covered by a reason above."]
    (ROOT / "contract" / "COVERAGE.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"routes={len(routes)} no_success={len(no_success)} gateway_tools_missing={missing}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
