"""Generate the static OOXML format assets; no recorded business data is emitted."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "dotnet" / "docs" / "package-probe"
TARGET = ROOT / "dotnet" / "src" / "TaxCredit.Application" / "Features" / "ClaimsArtifactsRules" / "Packages"
PARTS = [
    ("App", "docProps/app.xml"),
    ("Theme", "xl/theme/theme1.xml"),
    ("Styles", "xl/styles.xml"),
    ("Relationships", "_rels/.rels"),
    ("Workbook", "xl/workbook.xml"),
    ("WorkbookRelationships", "xl/_rels/workbook.xml.rels"),
    ("ContentTypes", "[Content_Types].xml"),
]


def main():
    TARGET.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Static OOXML assets compatible with the existing openpyxl workbook format.",
        "// Generated by dotnet/docs/generate_package_templates.py; no business rows.",
        "// Copyright (c) 2010 openpyxl; MIT notice: dotnet/docs/openpyxl-assets-LICENSE.txt.",
        "namespace TaxCredit.Application.Features.ClaimsArtifactsRules.Packages;",
        "",
        "internal static class WorkbookParts",
        "{",
    ]
    for name, file in PARTS:
        text = (SOURCE / file).read_text(encoding="utf-8")
        # A C# raw multiline literal excludes its opening and closing line endings.
        lines += [f'    internal const string {name} = """', text, '""";', ""]
    lines += ["}", ""]
    (TARGET / "WorkbookParts.Generated.cs").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
