using System.Text;
using System.Text.RegularExpressions;

namespace TaxCredit.Parity.Tests;

/// <summary>
/// Generates <c>docs/pack-validation-deviations.md</c> from the golden and the live library: every place where the .NET JSON Schema library words,
/// counts or orders a violation differently from Python's <c>jsonschema</c>. Nothing in the output is typed by hand, so it cannot drift from the
/// measurement; <see cref="PackValidationParityTests"/> fails when the file on disk is not what this produces.
/// </summary>
internal static partial class PackValidationDeviationReport
{
    public const string LibraryName = "JsonSchema.Net 8.0.5 (MIT)";

    public static string Path { get; } = System.IO.Path.Combine(Directory.GetParent(GoldenFiles.ParityDirectory)!.FullName, "dotnet", "docs", "pack-validation-deviations.md");

    /// <summary>Message to a comparable shape: quoted text, bracketed groups (any depth), numbers and Python literals become placeholders.</summary>
    public static string Pattern(string message)
    {
        var sb = new StringBuilder();
        for (var i = 0; i < message.Length; i++)
        {
            var c = message[i];
            if (c is '[' or '{')
            {
                i = SkipGroup(message, i);
                sb.Append("<v>");
            }
            else if (c is '\'' or '"')
            {
                i = SkipQuoted(message, i);
                sb.Append("<v>");
            }
            else
            {
                sb.Append(c);
            }
        }

        return Literal().Replace(Number().Replace(sb.ToString(), "<n>"), "<v>");
    }

    private static int SkipQuoted(string text, int start)
    {
        for (var i = start + 1; i < text.Length; i++)
        {
            if (text[i] == '\\')
            {
                i++;
            }
            else if (text[i] == text[start])
            {
                return i;
            }
        }

        return text.Length - 1;
    }

    private static int SkipGroup(string text, int start)
    {
        var depth = 0;
        for (var i = start; i < text.Length; i++)
        {
            if (text[i] is '\'' or '"')
            {
                i = SkipQuoted(text, i);
            }
            else if (text[i] is '[' or '{')
            {
                depth++;
            }
            else if (text[i] is ']' or '}' && --depth == 0)
            {
                return i;
            }
        }

        return text.Length - 1;
    }

    public static string Build(IReadOnlyList<SchemaComparison> all, int semanticIssues, int semanticReports, string pythonSchemaVersion)
    {
        var sb = new StringBuilder();
        var invalid = all.Count(c => c.Python.Count > 0);
        var decision = all.Where(c => !c.DecisionMatches).ToList();
        var keys = all.Where(c => c.DecisionMatches && !c.KeysMatch).ToList();
        var counts = all.Where(c => c.KeysMatch && !c.CountMatches).ToList();
        var order = all.Where(c => c.KeysMatch && !c.OrderMatches).ToList();
        sb.Append("# Rule-pack schema validation: deviations of the .NET library from Python's `jsonschema`\n\n");
        sb.Append("<!-- Generated by PackValidationParityTests (PackValidationDeviationReport). Do not edit by hand: run the test with TEST_UPDATE_DEVIATIONS=1. -->\n\n");
        sb.Append($"Python oracle: `jsonschema` {pythonSchemaVersion}, Draft 2020-12, against `backend/rules/schema/rule-pack.schema.json`. .NET: {LibraryName} behind `IJsonSchemaValidator` (adapter: `JsonSchemaPackValidator`).\n");
        sb.Append($"Corpus: {all.Count} documents in `parity/goldens/pack_validation.jsonl.gz` ({invalid} invalid under Python), exported by `parity/export_pack_validation.py`.\n\n");
        sb.Append("What the owner has to decide: whether the exact text, the number of violations or their order at one path matters to any consumer. The accept/reject decision, the failing keyword and the path are held to Python's and are tested as hard equality.\n\n");
        sb.Append("## Scorecard\n\n| Rule | Documents | Result |\n|---|---|---|\n");
        sb.Append($"| Accept/reject decision (hard) | {all.Count} | {all.Count - decision.Count} agree, {decision.Count} differ |\n");
        sb.Append($"| Distinct (keyword, path) pairs (hard) | {all.Count} | {all.Count - decision.Count - keys.Count} agree, {decision.Count + keys.Count} differ |\n");
        sb.Append($"| Number of violations (measured) | {all.Count(c => c.KeysMatch)} | {all.Count(c => c.KeysMatch) - counts.Count} agree, {counts.Count} differ |\n");
        sb.Append($"| Order of the distinct pairs (measured) | {all.Count(c => c.KeysMatch)} | {all.Count(c => c.KeysMatch) - order.Count} agree, {order.Count} differ |\n");
        sb.Append($"| Message wording (measured) | {all.Count(c => c.KeysMatch && c.Python.Count > 0)} invalid documents | see the patterns below |\n");
        sb.Append($"| Semantic issues (hard, bit for bit) | {semanticReports} reports | {semanticIssues} issues, 0 differ |\n\n");
        Section(sb, "Documents where the decision differs", decision, c => $"Python {(c.Python.Count == 0 ? "accepts" : "rejects")}, .NET {(c.Library.Count == 0 ? "accepts" : "rejects")}");
        Section(sb, "Documents where the distinct (keyword, path) pairs differ", keys, c => $"python-only: {string.Join("; ", c.PythonKeys.Select(v => v.Identity).Except(c.LibraryKeys.Select(v => v.Identity)))}; .NET-only: {string.Join("; ", c.LibraryKeys.Select(v => v.Identity).Except(c.PythonKeys.Select(v => v.Identity)))}");
        Wording(sb, all);
        Counting(sb, counts);
        Ordering(sb, order);
        sb.Append("## Closed in the adapter (exact, so not deviations)\n\n");
        sb.Append("- `oneOf`: the library lists the failing branches, lists branches of a `oneOf` that passed, and lists nothing when several branches match. The adapter reports one `oneOf` violation at the object, as Python does. Its wording is the adapter's (see the wording table).\n");
        sb.Append("- `propertyNames`: the library appends the property name to the instance location; Python reports the object. The adapter removes the last segment.\n");
        sb.Append("- A `false` schema (`extends`, `inherits`, `base`, `base_year` in a year pack) has no keyword in Python (`validator is None`); the adapter reports `null`.\n");
        sb.Append("- `minLength`: the library counts text elements (a letter plus its accent is one); Python counts code points. A `minLength` finding the code points satisfy is dropped, so `e` + U+0301 is long enough for a minimum of 2 in both.\n");
        sb.Append("- Regular expressions: the library runs patterns in .NET ECMAScript mode, where `\\s` is ASCII-only, and Python reads `\\s` as `str.isspace()` (U+001C..U+001F, U+0085, U+00A0 and the Unicode spaces). The adapter translates `\\s` and `\\S` in the schema's patterns; `$` and the character classes in use agree.\n");
        sb.Append("- A `false` schema reached through `properties` is reported by Python at the OBJECT, not at the rejected property, because `jsonschema` yields that error without the property path. The adapter reports the object too.\n");
        sb.Append("- An array index and an object key share the pointer syntax; the adapter resolves each segment against the document so `\"0\"` and `0` stay different paths.\n");
        return sb.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    private static void Section(StringBuilder sb, string title, List<SchemaComparison> items, Func<SchemaComparison, string> describe)
    {
        sb.Append($"## {title}: {items.Count}\n\n");
        if (items.Count == 0)
        {
            sb.Append("None.\n\n");
            return;
        }

        sb.Append("| Document | Detail |\n|---|---|\n");
        foreach (var item in items.Take(60))
        {
            sb.Append($"| {Cell(item.Source.Label)} | {Cell(describe(item))} |\n");
        }

        sb.Append(items.Count > 60 ? $"\n{items.Count - 60} more not listed.\n\n" : "\n");
    }

    private static void Wording(StringBuilder sb, IReadOnlyList<SchemaComparison> all)
    {
        var table = new SortedDictionary<string, (int Count, string PythonExample, string LibraryExample)>(StringComparer.Ordinal);
        foreach (var comparison in all.Where(c => c.KeysMatch))
        {
            foreach (var key in comparison.PythonKeys)
            {
                var python = comparison.Python.First(v => v.Identity == key.Identity);
                var library = comparison.Library.First(v => v.Identity == key.Identity);
                var id = $"{key.Keyword ?? "(false schema)"} | {Pattern(python.Message)} | {Pattern(library.Message)}";
                table[id] = table.TryGetValue(id, out var seen) ? (seen.Count + 1, seen.PythonExample, seen.LibraryExample) : (1, Short(python.Message), Short(library.Message));
            }
        }

        var different = table.Where(kv => kv.Key.Split(" | ")[1] != kv.Key.Split(" | ")[2]).ToList();
        sb.Append($"## Message wording: {different.Count} distinct deviating patterns\n\n");
        sb.Append("A pattern replaces quoted text, lists, objects and numbers by `<v>` / `<n>`. Counted per distinct (keyword, path) in a document. Messages that already read the same are not listed.\n\n");
        sb.Append("| Keyword | Python pattern | .NET pattern | Count | Python example | .NET example |\n|---|---|---|---|---|---|\n");
        foreach (var (id, row) in different)
        {
            var parts = id.Split(" | ");
            sb.Append($"| `{parts[0]}` | {Cell(parts[1])} | {Cell(parts[2])} | {row.Count} | {Cell(row.PythonExample)} | {Cell(row.LibraryExample)} |\n");
        }

        sb.Append('\n');
    }

    private static void Counting(StringBuilder sb, List<SchemaComparison> counts)
    {
        sb.Append($"## Number of violations differs: {counts.Count} documents\n\n");
        var kinds = counts.GroupBy(c => string.Join(", ", c.PythonKeys.Where(k => c.Python.Count(v => v.Identity == k.Identity) != c.Library.Count(v => v.Identity == k.Identity)).Select(k => k.Keyword).Distinct().Order(StringComparer.Ordinal)))
            .OrderBy(g => g.Key, StringComparer.Ordinal).ToList();
        if (kinds.Count == 0)
        {
            sb.Append("None.\n\n");
            return;
        }

        sb.Append("Python reports `required` once per missing name; the library reports it once per object, naming every missing property in one message. The same (keyword, path) is reported by both, so the decision and the pairs agree.\n\n| Keywords reported a different number of times | Documents | Example |\n|---|---|---|\n");
        foreach (var group in kinds)
        {
            sb.Append($"| `{group.Key}` | {group.Count()} | {Cell(group.First().Source.Label)} |\n");
        }

        sb.Append('\n');
    }

    private static void Ordering(StringBuilder sb, List<SchemaComparison> order)
    {
        sb.Append($"## Order differs: {order.Count} documents\n\n");
        if (order.Count == 0)
        {
            sb.Append("None.\n\n");
            return;
        }

        sb.Append("Both sides sort by absolute path (stable). Where several violations share a path, Python keeps the order in which it walked the schema keywords and the library keeps its own, so the pair of violations at that path swaps. The set at each path is the same.\n\n");
        sb.Append("| Pair at one path (Python order) | Documents | Example |\n|---|---|---|\n");
        foreach (var group in order.GroupBy(FirstSwap).OrderBy(g => g.Key, StringComparer.Ordinal).Take(40))
        {
            sb.Append($"| {Cell(group.Key)} | {group.Count()} | {Cell(group.First().Source.Label)} |\n");
        }

        sb.Append('\n');
    }

    private static string FirstSwap(SchemaComparison c)
    {
        for (var i = 0; i < Math.Min(c.PythonKeys.Count, c.LibraryKeys.Count); i++)
        {
            if (c.PythonKeys[i].Identity != c.LibraryKeys[i].Identity)
            {
                return $"{c.PythonKeys[i].Keyword} before {c.LibraryKeys[i].Keyword} at /{c.PythonKeys[i].PathKey}";
            }
        }

        return "different length";
    }

    private static string Short(string text) => text.Length <= 90 ? text : text[..90] + "...";

    private static string Cell(string text) => text.Replace("|", "\\|", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);

    [GeneratedRegex(@"-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?")]
    private static partial Regex Number();

    [GeneratedRegex(@"\b(?:True|False|None)\b")]
    private static partial Regex Literal();
}
