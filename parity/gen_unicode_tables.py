"""Generate TaxCredit.Domain/Numerics/PyUnicodeTables.g.cs from the oracle interpreter.

Why: .NET has no equivalent of Python's full (SpecialCasing) str.upper() and its
Unicode version differs, so the port carries the exact mapping table of the
interpreter that is the oracle. The parity tests then check every one of the
1.1M code points against exported vectors, so a stale table fails loudly.

Usage: python parity/gen_unicode_tables.py   (writes the .g.cs; deterministic)
"""
from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import oracle  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "dotnet" / "src" / "TaxCredit.Domain" / "Numerics" / "PyUnicodeTables.g.cs"


def chunked(values: list[int], per_line: int = 16) -> str:
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("        " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


def main() -> int:
    oracle.require()
    keys, offsets, data = [], [], []
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        up = chr(c).upper()
        if up != chr(c):
            keys.append(c)
            offsets.append(len(data))
            data.extend(ord(x) for x in up)
            data.append(-1)  # terminator keeps each expansion self-delimiting
    spaces = [c for c in range(0x110000) if not (0xD800 <= c <= 0xDFFF) and chr(c).isspace()]
    text = f"""// <auto-generated>
// Generated by parity/gen_unicode_tables.py from CPython {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}).
// Do not edit; regenerate. Verified code point by code point in TaxCredit.Parity.Tests.
// </auto-generated>
#nullable enable
namespace TaxCredit.Domain.Numerics;

/// <summary>Case-mapping and whitespace tables extracted from the Python oracle.</summary>
internal static class PyUnicodeTables
{{
    /// <summary>Unicode version of the interpreter the tables were generated from.</summary>
    internal const string UnicodeVersion = "{unicodedata.unidata_version}";

    /// <summary>Code points whose <c>str.upper()</c> differs from themselves, ascending.</summary>
    internal static readonly int[] UpperKeys =
    [
{chunked(keys)}
    ];

    /// <summary>Start index into <see cref="UpperData"/> of each key's expansion.</summary>
    internal static readonly int[] UpperOffsets =
    [
{chunked(offsets)}
    ];

    /// <summary>Concatenated expansions, each terminated by -1.</summary>
    internal static readonly int[] UpperData =
    [
{chunked(data)}
    ];

    /// <summary>Code points for which <c>str.isspace()</c> is true, ascending.</summary>
    internal static readonly int[] Whitespace =
    [
{chunked(spaces)}
    ];
}}
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text.replace("\r\n", "\n"), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(keys)} upper keys, {len(spaces)} whitespace)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
